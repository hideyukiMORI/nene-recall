// Package lexical は語彙検索のためのテキスト分割の契約を定める。
//
// 🔴 このパッケージは契約だけを持ち、実装はサブパッケージに置く
// (internal/lexical/bigram)。埋め込みで同じ形を採った理由がそのまま当てはまる
// (docs/adr/0012-embedding-implementations-live-in-subpackages.md)。契約は
// 「テキストをトークン列に分割する」という意味だけを持つべきで、その意味に
// 辞書ファイルの読み込みも Unicode 表の外部依存も含まれない。ARC-002 の
// pure-core は契約パッケージ本体に掛かり、実装サブパッケージには掛からない。
//
// 分割器を差し替えても呼び出し側が変わらないよう、インタフェースで隔離する。
// 要件定義 Q-2（bigram か形態素か）は ADR 0009 の評価で決着させる未決事項であり、
// 決着するまで「どちらでも差し替えられる」ことが設計上の要求である。
package lexical

// Tokenizer はテキストを語彙一致のためのトークン列に分割する。
//
// 🔴 取り込みと検索は必ず同じ Tokenizer を通す。取り込み側と検索側で分割が
// 違うと、同じ語を書いたつもりのチャンクとクエリが別のトークンになり、
// 「エラーにならないまま語彙スコアが常に 0」という壊れ方をする。これは
// ADR 0005 が埋め込みについて記録した罠と同じ形で、単一の分割器で開発して
// いる限り一切表面化しない。
type Tokenizer interface {
	// Tokenize は text をトークン列に分割する。
	//
	// 🔴 決定的であること。同じ入力からは常に同じ出力を返す。時計も乱数も
	// 環境も読まない。ストアはこの出力を保存し、検索時に同じ関数を通した
	// 結果と突き合わせるので、揺れる実装は保存済みの索引を静かに無効にする。
	//
	// 🔴 トークンは空白文字を含んではならない。ストアはトークン列を空白区切りの
	// 1本の文字列として保存する（PostgreSQL の to_tsvector に渡す形）ので、
	// 空白を含むトークンは DB の中で2つ以上のレキシームに割れる。Go 側が
	// 1トークンのつもりのものが DB では別物になる、という検出しにくい壊れ方をする。
	//
	// 🔴 トークンは全文検索クエリのメタ文字を含んではならない。具体的には
	// & | ! ( ) : * < > と引用符で、PostgreSQL の tsquery 構文で意味を持つ。
	// 含めると検索式の組み立てが構文エラーになる。ストア側は契約違反を
	// エラーとして表面化させる（黙って落とすと語彙スコアが静かに欠ける）。
	//
	// 空のトークン列を返してよい。絵文字だけのクエリなど、分割できる語が
	// 1つも無い入力は正常な入力である。呼び出し側はこれをエラーにせず、
	// 語彙スコア 0 として扱う。
	Tokenize(text string) []string

	// ID は "bigram:nfkc-lower:v1" のような識別子を返す。
	//
	// 🔴 分割規則を変えたら ID も変える。保存済みのトークン列は古い規則で
	// 作られており、新しい規則で分割したクエリとは噛み合わない。次元が
	// 一致していても別モデルのベクトルが比較できないのと同じ性質で、
	// Embedder.ID() と同じ役割をこの識別子が果たす
	// (docs/adr/0005-embedding-provider-is-pluggable.md)。
	//
	// ストアはこの値を行ごとに記録し、不一致をエラーにする。
	ID() string
}
